// 最適化の実機比較を「焼き直さずに」行うためのスイッチ。
//
// このプロジェクトでは、最適化が効いたかどうかを **実機でしか判定できない**。
// ホストのコンパイラは TU を跨ぐ呼び出しも潰せるので差が出ず、実際
// 「ホストで誤差内、実機で +12.8%」という変更があった
// (docs/knowledge/cores3-emulator-runtime.md)。
//
// ところが実機の実効クロックは起動ごとに揺れる。SD の中身、PSRAM の
// 割り付け、温度がそれぞれ効く。焼き直して前後を比べると、この揺れが
// 最適化の効果と混ざる。実際、同じコードの計測が 3711 kHz と 3630 kHz に
// 分かれたことがある (起動直後の値を拾ったため)。
//
// そこで **同じ起動の中で切り替える**。音源の ON/OFF ('|') が既にこの形で、
// 「音を足すとどれだけ遅くなるか」を焼き直さずに測るために入れてある。
// 同じ手を最適化そのものへ広げる。1 回焼けば、5 秒ごとの実効クロックの
// 報告を挟みながら全ての組み合わせを順に測れる。
//
// Why not コンパイル時の #if にしないか: それだと組み合わせのぶんだけ
// 焼き直しが要る。本ファイルの目的は焼き直しを無くすことなので本末転倒。
//
// Why not std::atomic にしないか: この値は **毎命令読まれる**。atomic の
// 読み出しは最適化を跨げないので、測ろうとしている当のホットループに
// 計測器のコストが乗る。書くのはシリアルを受けるタスク、読むのは
// エミュレーションコアだが、遷移が 1 スライス遅れて効いても計測には
// 影響しない (5 秒ぶんの平均を読む)。値は bool 1 つで、途中の状態が
// 無いので破れたバイトを読む心配も無い。
//
// **本番の既定は全て有効**。無効側は計測のためだけにある。

#ifndef X68K_CORE_PERF_SWITCH_H
#define X68K_CORE_PERF_SWITCH_H

#include <cstdint>

namespace x68k
{

// 毎命令通る経路の最適化を個別に切れるようにする。
//
// 各ビットは「速い側を通す」= 有効。落とすと、その最適化を入れる前と
// 同じ経路 (実呼び出し) に戻る。状態遷移はどちらでも同一なので、
// 差として出るのは速度だけになる。
struct PerfSwitch
{
    // Rtc::tick の速い側 (累算して閾値に届かなければ即戻る)。
    bool inlineRtcTick = true;
    // Crtc::tick の速い側 (加算と垂直帰線の比較だけ)。
    bool inlineCrtcTick = true;
    // Mfp::tick の速い側 (1 回だけ減ってタイムアウトしない経路)。
    bool inlineMfpTimer = true;

    // 全て有効かどうか。ログに出すときの短い表示に使う。
    [[nodiscard]] bool allEnabled() const
    {
        return inlineRtcTick && inlineCrtcTick && inlineMfpTimer;
    }
};

}  // namespace x68k

#endif  // X68K_CORE_PERF_SWITCH_H
