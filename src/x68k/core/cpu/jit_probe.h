// JIT の見込みを実機で測るための計測モード。**恒久的な機能ではない。**
//
// 動的再コンパイルは ESP32-S3 で数千行になる。着手する前に「どこまで
// 速くなりうるか」の上限を実測しておかないと、書き上げてから足りないと
// 分かる事態になる。このプロジェクトでは既に「プロファイル上で大きい」
// ことと「そこを削れる」ことが別だと何度も実測している
// (docs/knowledge/cores3-emulator-runtime.md)。
//
// JIT が消せるものと消せないものを分けて考える:
//
//   消せる  — 命令ごとのディスパッチ (switch と関数呼び出し)
//   消せる  — プリフェッチの維持 (fetch / refillPrefetch)
//   消せる  — サイクル数の加算と返却 (ブロック単位でまとめられる)
//   消せない — 実効アドレス計算とメモリアクセス (PSRAM 待ちは変わらない)
//   消せない — 演算そのものとフラグ計算
//   消せない — デバイスの tick と割り込み判定 (ブロック境界で必ず要る)
//
// そこで、消せる側だけを段階的に取り除いた状態で実効クロックを測る。
// 得られる数字は **JIT が到達しうる上限** であって、JIT の実測値ではない。
// 上限が 10MHz に届かないなら、JIT を書いても届かない。

#ifndef X68K_CORE_CPU_JIT_PROBE_H
#define X68K_CORE_CPU_JIT_PROBE_H

namespace x68k
{

// 計測モード。既定は kOff で、通常の実行と完全に同じ経路を通る。
enum class JitProbeMode
{
    // 通常。何も細工しない。
    kOff = 0,

    // ディスパッチを外す。命令語を読んで switch を引く代わりに、
    // 直前に実行した命令と同じ実装を呼ぶ。
    //
    // JIT はブロック内の命令列を直線コードに並べるので、命令ごとの
    // switch とサイクル表の引き当てが消える。その分だけを模す。
    //
    // **状態は正しくならない。** 実行される命令列が変わるので、
    // ゲストは正常に動かない。速度の上限を見るためだけのモード。
    kNoDispatch,

    // 命令の実行そのものを空回しにする。1 命令 4 サイクルとして
    // 時間だけ進める。ループ運営・tickDevices・割り込み判定だけが残る。
    //
    // これは前回セッションで一度測っており、当時 10000 kHz だった。
    // 現在のコードでも同じ上限が出るかを確かめ直すために残す。
    kNullExec,
};

}  // namespace x68k

#endif  // X68K_CORE_CPU_JIT_PROBE_H
